/**
 * Creates the app's voice recordings with ElevenLabs (voice "Jawad") and writes
 * src/data/voice.ts, which maps each text to its recording.
 *
 *   cd mobile && npx tsx --tsconfig tsconfig.json scripts/make-voice.ts [--dry]
 *
 * Only missing files are generated, so after adding new duas, words or clues
 * just run it again. The API key comes from the cloud environment's network
 * secret for api.elevenlabs.io (sent by the proxy), so no key is needed here.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { DUAS } from '@/data/duas';
import { RING_CLUES } from '@/data/letter-ring-clues';
import { MEMORY_LEVELS } from '@/data/memory-levels';
import { GUESS_WORDS } from '@/data/word-guess-words';

const VOICE_ID = 'JoySr0ZYKEotnyhsN3Fi'; // "Jawad - Friendly, Natural and Positive"
const MODEL = 'eleven_v4'; // supports both Arabic and Azerbaijani
const ROOT = join(__dirname, '..');
const OUT_DIR = join(ROOT, 'assets', 'voice');
const DRY = process.argv.includes('--dry');

type Entry = { key: string; file: string; text: string; lang: 'ar' | 'az' };

/** ASCII file-name part for Azerbaijani text. */
function slug(text: string): string {
  const map: Record<string, string> = { ə: 'e', ç: 'c', ğ: 'g', ı: 'i', ö: 'o', ş: 's', ü: 'u', İ: 'i', I: 'i' };
  return text
    .replace(/[əçğıöşüİI]/g, (c) => map[c] ?? c)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

/** Text as it should be spoken: no brackets, guillemets or quotes. */
const spoken = (text: string) => text.replace(/[[\]()«»"]/g, '').replace(/\s+/g, ' ').trim();

const entries: Entry[] = [];
const add = (key: string, file: string, text: string, lang: 'ar' | 'az') => {
  if (entries.some((e) => e.file === file)) throw new Error(`Duplicate file name ${file}`);
  entries.push({ key, file, text: spoken(text), lang });
};

for (const d of DUAS) {
  d.parts.forEach((p, i) => {
    add(`dua:${d.id}:${i}:ar`, `dua-${d.id}-${i}-ar.mp3`, p.arabic, 'ar');
    add(`dua:${d.id}:${i}:az`, `dua-${d.id}-${i}-az.mp3`, p.meaning, 'az');
  });
}
for (const w of GUESS_WORDS) add(`wg:${w.word}`, `wg-${slug(w.word)}.mp3`, w.clue, 'az');
for (const c of RING_CLUES) add(`lr:${c.letter}:${c.answer}`, `lr-${slug(c.letter)}-${slug(c.answer)}.mp3`, c.clue, 'az');
for (const l of MEMORY_LEVELS) {
  for (const it of l.items) {
    add(`mem:${l.id}:${it.id}`, `mem-${l.id}-${it.id}.mp3`, `${it.name}. ${it.info}`, 'az');
    add(`memname:${l.id}:${it.id}`, `mem-${l.id}-${it.id}-name.mp3`, it.name, 'az');
  }
}

mkdirSync(OUT_DIR, { recursive: true });
const missing = entries.filter((e) => !existsSync(join(OUT_DIR, e.file)) || statSync(join(OUT_DIR, e.file)).size < 1000);
const chars = missing.reduce((n, e) => n + e.text.length, 0);
console.log(`${entries.length} recordings, ${missing.length} missing (${chars} characters to generate).`);

if (!DRY) {
  for (const [i, e] of missing.entries()) {
    const body = JSON.stringify({
      text: e.text,
      model_id: MODEL,
      language_code: e.lang,
      voice_settings: { stability: 0.5, similarity_boost: 0.8 },
    });
    const out = join(OUT_DIR, e.file);
    for (let attempt = 1; ; attempt++) {
      try {
        const code = execFileSync(
          'curl',
          [
            '-sS', '-o', out, '-w', '%{http_code}', '-X', 'POST',
            `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_64`,
            '-H', 'xi-api-key: proxy-injected', '-H', 'Content-Type: application/json', '--data-binary', '@-',
          ],
          { input: body },
        ).toString();
        if (code !== '200') throw new Error(`HTTP ${code}`);
        console.log(`[${i + 1}/${missing.length}] ${e.file}`);
        break;
      } catch (err) {
        if (attempt >= 4) throw new Error(`${e.file}: ${String(err)}`);
        execFileSync('sleep', [String(attempt * 5)]);
      }
    }
  }
}

// Write the map (only files that exist, so a partial run still builds).
const have = new Set(readdirSync(OUT_DIR));
const lines = entries
  .filter((e) => have.has(e.file))
  .map((e) => `  ${JSON.stringify(e.key)}: require('../../assets/voice/${e.file}'),`);
writeFileSync(
  join(ROOT, 'src', 'data', 'voice.ts'),
  `// Generated by scripts/make-voice.ts (ElevenLabs, voice "Jawad") — do not edit by hand.
import type { AudioSource } from 'expo-audio';

export const VOICE: Record<string, AudioSource> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote src/data/voice.ts with ${lines.length} recordings.`);
