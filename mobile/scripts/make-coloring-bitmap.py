"""
Turns a black-and-white line drawing into a tap-to-fill coloring page.

  python3 scripts/make-coloring-bitmap.py <id> <source image>

Writes (from mobile/):
  assets/coloring/<id>/line.png       the lines, transparent elsewhere (drawn on top)
  assets/coloring/<id>/r<N>.png       one white mask per fillable area (tinted in the app)
  src/data/coloring-bitmaps/<id>.ts   sizes, mask positions and a small tap map

Tiny enclosed areas (dome lattice, petals) are grouped with their small
neighbours so one tap fills the whole group.
"""
import json
import os
import sys

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

WORK_W = 768        # resolution of the region masks
LINE_W = 1024       # resolution of the line art
SMALL = 260         # areas smaller than this (px at WORK_W) get grouped
MIN_AREA = 30       # groups smaller than this are not fillable
MAP_STEP = 4        # tap map = work resolution / MAP_STEP

pid, src = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_dir = os.path.join(root, 'assets', 'coloring', pid)
os.makedirs(out_dir, exist_ok=True)
for f in os.listdir(out_dir):
    os.remove(os.path.join(out_dir, f))

img = Image.open(src).convert('L')
W0, H0 = img.size

# Line art: darkness becomes alpha.
lw, lh = LINE_W, round(H0 * LINE_W / W0)
g = np.asarray(img.resize((lw, lh), Image.LANCZOS)).astype(np.float32)
alpha = np.clip((235 - g) / 150, 0, 1)
line = np.zeros((lh, lw, 4), np.uint8)
line[..., 0:3] = 0x2B
line[..., 3] = (alpha * 255).astype(np.uint8)
Image.fromarray(line, 'RGBA').save(os.path.join(out_dir, 'line.png'), optimize=True)

# Regions at work resolution.
ww, wh = WORK_W, round(H0 * WORK_W / W0)
g = np.asarray(img.resize((ww, wh), Image.LANCZOS))
lines = g < 165
lines = ndi.binary_dilation(lines, iterations=1)  # close small gaps in the drawing
labels, n = ndi.label(~lines)
areas = ndi.sum(np.ones_like(labels), labels, index=np.arange(n + 1))

# Group small areas that sit next to each other (across a thin line).
small_ids = np.where((areas < SMALL) & (np.arange(n + 1) > 0))[0]
small_mask = np.isin(labels, small_ids)
clusters, _ = ndi.label(ndi.binary_dilation(small_mask, iterations=3))
group = np.zeros_like(labels)
next_id = 1
remap = {}
for lab in range(1, n + 1):
    if areas[lab] >= SMALL:
        remap[('big', lab)] = next_id
        next_id += 1
ys, xs = np.nonzero(labels)
for y, x in zip(ys, xs):
    lab = labels[y, x]
    key = ('big', lab) if areas[lab] >= SMALL else ('small', clusters[y, x])
    if key not in remap:
        remap[key] = next_id
        next_id += 1
    group[y, x] = remap[key]

# Drop specks and renumber densely.
gareas = ndi.sum(np.ones_like(group), group, index=np.arange(next_id))
keep = [i for i in range(1, next_id) if gareas[i] >= MIN_AREA]
dense = np.zeros(next_id, np.int32)
for k, i in enumerate(keep):
    dense[i] = k + 1
group = dense[group]

regions = []
objs = ndi.find_objects(group)
for k, sl in enumerate(objs):
    if sl is None:
        continue
    gid = k + 1
    y0, y1 = max(sl[0].start - 3, 0), min(sl[0].stop + 3, wh)
    x0, x1 = max(sl[1].start - 3, 0), min(sl[1].stop + 3, ww)
    m = group[y0:y1, x0:x1] == gid
    # Grow the mask under the surrounding lines only, so no color bleeds.
    m = m | (ndi.binary_dilation(m, iterations=3) & lines[y0:y1, x0:x1])
    a = np.zeros(m.shape + (4,), np.uint8)
    a[..., 0:3] = 255
    a[..., 3] = m * 255
    Image.fromarray(a, 'RGBA').save(os.path.join(out_dir, f'r{gid}.png'), optimize=True)
    regions.append((gid, x0, y0, x1 - x0, y1 - y0))

# Tap map, run-length encoded: [value, count, value, count, ...].
small = group[MAP_STEP // 2::MAP_STEP, MAP_STEP // 2::MAP_STEP]
flat = small.flatten().tolist()
rle = []
for v in flat:
    if rle and rle[-2] == v:
        rle[-1] += 1
    else:
        rle += [v, 1]

ts_dir = os.path.join(root, 'src', 'data', 'coloring-bitmaps')
os.makedirs(ts_dir, exist_ok=True)
with open(os.path.join(ts_dir, f'{pid}.ts'), 'w') as f:
    f.write('// Generated by scripts/make-coloring-bitmap.py — do not edit by hand.\n')
    f.write("import type { BitmapPicture } from '@/data/coloring-bitmaps/types';\n\n")
    f.write('const picture: BitmapPicture = {\n')
    f.write(f'  width: {ww},\n  height: {wh},\n')
    f.write(f"  line: require('../../../assets/coloring/{pid}/line.png'),\n")
    f.write('  regions: [\n')
    for gid, x, y, w, h in regions:
        f.write(f"    {{ x: {x}, y: {y}, w: {w}, h: {h}, src: require('../../../assets/coloring/{pid}/r{gid}.png') }},\n")
    f.write('  ],\n')
    f.write(f'  map: {{ w: {small.shape[1]}, h: {small.shape[0]}, step: {MAP_STEP}, rle: {json.dumps(rle, separators=(",", ":"))} }},\n')
    f.write('};\n\nexport default picture;\n')

print(f'{len(regions)} regions, map {small.shape}, rle {len(rle)}')
